/** A presigned upload the app performs itself: `PUT url` with `headers`, before `expiresAt`. */
export type PresignedUpload = { url: string; method: 'PUT'; headers: Record<string, string>; expiresAt: string };

/** Per-request context: the engine's own base URL (`https://host`), for drivers that serve files themselves. */
export type StorageRequestContext = { baseUrl: string };

/** A stored object's size and type, as the storage reports them. */
export type StoredObject = { size: number; contentType: string | null };

/**
 * Private object storage for moment photos (docs/app-moments-spec.md §2). Clients only ever get
 * short-lived signed URLs: PUT for 15 minutes, GET for 1 hour.
 */
export interface ObjectStorage {
  readonly driver: 'local' | 's3';
  presignUpload(key: string, file: { contentType: string; byteSize: number }, context: StorageRequestContext): Promise<PresignedUpload>;
  presignDownload(key: string, context: StorageRequestContext): Promise<string>;
  /** The object's size and type, or null if it doesn't exist. */
  stat(key: string): Promise<StoredObject | null>;
  /** Deletes the object; a missing one is not an error. */
  delete(key: string): Promise<void>;
  /** The object's first `length` bytes (fewer if it's shorter), or null if it doesn't exist. */
  readStart(key: string, length: number): Promise<Buffer | null>;
  /** Rewrites the object's stored Content-Type (S3: CopyObject onto itself, metadata REPLACE). */
  setContentType(key: string, contentType: string): Promise<void>;
}

export const OBJECT_STORAGE = Symbol('OBJECT_STORAGE');

export const UPLOAD_URL_TTL_SECONDS = 15 * 60;
export const DOWNLOAD_URL_TTL_SECONDS = 60 * 60;
/** Object keys are generated by the engine: `moments/<user id>/<moment id>.jpg` or `avatars/<user id>/<uuid>.jpg`. */
export const OBJECT_KEY = /^(moments|avatars)\/[0-9a-f-]{36}\/[0-9a-f-]{36}\.jpg$/;
export const momentObjectKey = (userId: string, momentId: string) => `moments/${userId}/${momentId}.jpg`;
/** Profile pictures live in their own folder: `avatars/<user id>/<uuid>.jpg`. */
export const avatarObjectKey = (userId: string, id: string) => `avatars/${userId}/${id}.jpg`;
